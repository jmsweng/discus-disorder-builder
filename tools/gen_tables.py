"""Generate the page's data tables from discus-python, so the page and its Python back end cannot drift.

    python tools/gen_tables.py            # rewrite src/discus_names.js from discuspdf.atom_names
    python tools/gen_tables.py --check    # exit 1 if src/discus_names.js or the wavelength symbols differ

Needs discus-python (discuspdf) importable, at the version DISCUSPDF_REF in src/core.js points to.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES_JS = ROOT / "src" / "discus_names.js"


def names_js() -> str:
    from discuspdf import atom_names
    rows = atom_names.discus_name_rows(scattering_only=False)
    body = json.dumps([[n, e, b] for n, e, b in rows], separators=(",", ":"))
    return ("/* GENERATED by tools/gen_tables.py from discus-python's discuspdf.atom_names; do not edit by hand.\n"
            "   Atom names DISCUS 6.23.01 knows (lib_f90/element_data_mod.f90: per_name, per_element, per_bcoh), with the\n"
            "   element whose X-ray form factor it uses and the coherent neutron b (fm). VOID and the names whose element is\n"
            f"   VOID do not scatter. Source file SHA-256 {atom_names.SOURCE_SHA256}. */\n"
            "(function (root) {\n\"use strict\";\n"
            f"const DISCUS_NAMES = {body};\n"
            "if (typeof module !== \"undefined\" && module.exports) module.exports = DISCUS_NAMES; else root.DB_DISCUS = DISCUS_NAMES;\n"
            "})(typeof window !== \"undefined\" ? window : globalThis);\n")


def wavelength_symbols_in_core() -> set[str]:
    core = (ROOT / "src" / "core.js").read_text(encoding="utf-8")
    block = re.search(r"const WAVELENGTH_SYMBOLS = \{([^}]*)\}", core).group(1)
    return set(re.findall(r"(\w+):", block))


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    from discuspdf.fourier_macro import WAVELENGTHS
    problems = []
    if wavelength_symbols_in_core() != set(WAVELENGTHS):
        problems.append(f"core.js WAVELENGTH_SYMBOLS differ from discuspdf WAVELENGTHS {sorted(WAVELENGTHS)}")
    text = names_js()
    if "--check" in argv:
        if NAMES_JS.read_text(encoding="utf-8") != text:
            problems.append("src/discus_names.js is not the generated table (run tools/gen_tables.py)")
    else:
        NAMES_JS.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {NAMES_JS.relative_to(ROOT)}")
    for p in problems:
        print("ERROR:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
